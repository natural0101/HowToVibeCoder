        Current = lang;
        if(Raylib_cs.Raylib.IsWindowReady()) Raylib_cs.Raylib.SetWindowTitle(WindowTitle);
        AudioMusicSystem.LanguageChanged();
        VisualEngine3D.RefreshLanguage();
    }

