    private static readonly Regex Slot = new(@"\{(\d+)\}");
    private static readonly Dictionary<string,string> Fragments = BuildFragments();
    private static Dictionary<string,string> BuildFragments()
    {
        var result = new Dictionary<string,string>(StringComparer.Ordinal);
        foreach (var (ru,en) in English.Where(p => !Slot.IsMatch(p.Key)))
        {
            result[ru] = en;
            result.TryAdd(ru.ToUpperInvariant(), en.ToUpperInvariant());
        }
        return result;
    }

    private static readonly Regex Phrases = new(string.Join("|", Fragments.Keys.OrderByDescending(k => k.Length)
        .Select(k => k.Length == 1 ? @"(?<!\p{L})" + Regex.Escape(k) + @"(?!\p{L})" : Regex.Escape(k))));
    private static readonly (Regex Pattern,string English)[] Templates = English.Where(p => Slot.IsMatch(p.Key))
        .OrderByDescending(p => Slot.Replace(p.Key,"").Length).Select(p =>
        {
            var parts = Regex.Split(p.Key, @"\{\d+\}").Select(Regex.Escape);
            return (new Regex("^" + string.Join("(.+?)", parts) + "$", RegexOptions.CultureInvariant),p.Value);
        }).ToArray();
    private static readonly Dictionary<string,string> Cache = new();

    public static string Tr(string text)
    {
        if (!IsEn || string.IsNullOrEmpty(text)) return text;
        if (Fragments.TryGetValue(text,out var exact)) return exact;
        if (!text.Any(IsCyrillic)) return text;
        if (Cache.TryGetValue(text,out var cached)) return cached;
        string translated = TranslateComposite(text);
        if (Cache.Count >= 4096) Cache.Clear();
        Cache[text] = translated;
        return translated;
    }

    private static string TranslateComposite(string text)
    {
        foreach (var (pattern,english) in Templates)
        {
            var match = pattern.Match(text);
            if (match.Success)
                return Slot.Replace(english, p => Tr(match.Groups[1 + int.Parse(p.Groups[1].Value)].Value));
        }
        return Phrases.Replace(text, m => Fragments[m.Value]);
    }
