    internal static string RenderText(string value)
    {
        string result=Tr(value);
        if(CheckRenderLanguage && result is not ("Русский" or "Язык / Language") && result.Any(IsCyrillic))
            throw new InvalidDataException($"Missing English translation: {value} => {result}");
        return result;
    }
    private static bool IsCyrillic(char c) => c is >= '\u0400' and <= '\u04ff';

    public static GameLang Current { get; private set; } = GameLang.Ru;
